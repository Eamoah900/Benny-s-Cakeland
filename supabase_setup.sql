-- Benny Cakeland database setup for Supabase
-- Run this complete script in Supabase Dashboard > SQL Editor.

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin'))
);

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = auth.uid() and role = 'admin'
  );
$$;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price_ghs numeric(10,2),
  image_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_phone text not null,
  product_type text not null,
  needed_date date,
  details text,
  status text not null default 'pending'
    check (status in ('pending','confirmed','in_progress','completed','cancelled')),
  created_at timestamptz not null default now()
);

alter table public.user_roles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;

-- Public visitors may only see products marked active.
drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products"
on public.products for select to anon, authenticated
using (is_active = true or public.is_admin());

-- Only an admin can add, edit or remove products.
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products"
on public.products for all to authenticated
using (public.is_admin())
with check (public.is_admin());

-- Visitors can submit an order enquiry. No public read/update/delete access.
drop policy if exists "Visitors can submit orders" on public.orders;
create policy "Visitors can submit orders"
on public.orders for insert to anon, authenticated
with check (
  length(trim(customer_name)) between 1 and 100
  and length(trim(customer_phone)) between 5 and 30
  and length(trim(product_type)) between 1 and 100
);

-- Only admins can view and manage submitted orders.
drop policy if exists "Admins manage orders" on public.orders;
create policy "Admins manage orders"
on public.orders for all to authenticated
using (public.is_admin())
with check (public.is_admin());

-- Only admins can view role rows. Do not grant public role assignment.
drop policy if exists "Admins can view roles" on public.user_roles;
create policy "Admins can view roles"
on public.user_roles for select to authenticated
using (public.is_admin());

